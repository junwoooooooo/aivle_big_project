def ethical_hits(board_text: str) -> list[str]:
    """컨셉보드에서 윤리·가치 어휘를 찾는다. **막지 않는다 — 알린다.**

    우열 조사는 이 축이 대비의 축이면 차단했다. 거기서는 「그 축을 빼고 다시 물어라」가
    가능했지만, 여기서는 자극이 확정된 사업안 그 자체다. 친환경이 제품의 본질인 사업안을
    조사 자체에서 막는 것은 과하다. 대신 그 축의 반응을 믿지 말라고 값 옆에 적는다.
    """
    return sorted({term for term in ETHICAL_TERMS if term in board_text})


def build(board_text: str) -> list[str]:
    """결과에 실릴 경계 문구 전부. 비어 있을 수 없다."""
    notes = list(ALWAYS)
    notes.extend(INSTRUMENT_VERIFIED if INSTRUMENT_EQUIVALENCE_CONFIRMED
                 else INSTRUMENT_UNVERIFIED)
    if ethical_hits(board_text):
        notes.extend(ETHICAL_APPEAL)
    return notes
