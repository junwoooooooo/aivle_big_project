"""인터뷰 가이드 — 고정 9문항과 프롬프트 템플릿.

**이 파일을 고치면 계기가 바뀐다.** 응답은 문항 순서에 민감하다(합성 응답자 문헌의
일관된 관찰이고, 이 저장소도 위치편향 P=+1.0000 을 실측한 적이 있다). 순서를 고정해야
조사 간 비교가 자극 차이만 반영한다. `tests/test_interview_questions.py` 가 렌더 결과의
**바이트 동일성**을 검사한다 — 그 테스트가 깨지면 고칠 것은 테스트가 아니라 이 파일이다.

문항 순서는 IDI 표준을 따른다: 무편집 첫반응 → 이해 확인 → 긍정 → 부정 → 차별성 →
필요성 → 사용 장면 → 장벽 → 개선. **첫인상을 맨 앞에 두는 것이 설계의 핵심**이다.
뒤 문항이 생각을 오염시키기 전의 날것을 잡는 자리라, 앞으로 옮길 것도 뒤로 미룰 것도 없다.

2번(이해 확인)은 「반응이 나쁜 것」과 「설명이 나쁜 것」을 가르는 자리다. 여기서 오해가
쏟아지면 컨셉이 나쁜 게 아니라 컨셉보드가 나쁜 것이고, 고칠 곳이 완전히 다르다.

**파고들기를 문항에 내장했다(3·4·8번).** 조사원이 되묻는 것이 정성 조사의 본체인데
1인 1턴 구조라 되물을 기회가 없다. 그래서 「왜 그런지」·「무엇과 비교해서인지」·
「그게 없어지면 어떨지」를 질문 안에 넣었다 — 이유 사슬이 원문에 남아야 화면이
「가격이 비싸다 19명」에서 멈추지 않는다.
"""

QUESTIONS = (
    ("firstImpression", "첫인상", "방금 보신 것에 대해 떠오르는 대로 말씀해주세요."),
    ("restatement", "이해", "이 제품이 뭘 해주는 건지 본인 말로 설명해주시겠어요?"),
    ("like", "끌리는 점",
     "가장 마음에 드는 점은 뭔가요? 그게 왜 본인에게 중요한지도 말씀해주세요."),
    ("concern", "걸리는 점",
     "마음에 안 들거나 걸리는 점은요? 왜 걸리는지, 무엇과 비교해서 그런지도 말씀해주세요."),
    ("differentiation", "차별성",
     "지금 있는 것들과 뭐가 다르다고 느끼세요? 다른 게 없다면 없다고 말씀하셔도 됩니다."),
    ("relevance", "필요성",
     "이게 본인 상황에 필요한 물건인가요? 지금은 이 문제를 어떻게 해결하세요?"),
    ("usageScene", "사용 장면",
     "산다면 언제, 어떤 상황에서 쓸 것 같은지 상상해서 말씀해주세요."),
    ("barrier", "안 사는 이유",
     "만약 안 산다면, 가장 큰 이유는 뭘까요? 그 이유가 없어진다면 사실 것 같은지도 말씀해주세요."),
    ("suggestion", "바꾸고 싶은 것", "하나만 바꿀 수 있다면 뭘 바꾸시겠어요?"),
)

SYSTEM = "한국어로 답하세요."

_QUESTION_BLOCK = "\n".join(
    f"{index}. {title} — {text}" for index, (_, title, text) in enumerate(QUESTIONS, 1))

# 카드 본문과 컨셉보드 두 자리만 슬롯이다. 나머지는 한 글자도 바꾸지 않는다.
TEMPLATE = f"""{{CARD_TEXT}}

당신은 위 인물입니다. 조사원이 상품 설명 하나를 보여주고 몇 가지를 묻습니다.

--- 상품 설명 ---
{{BOARD}}
-----------------

{_QUESTION_BLOCK}

이 인물의 형편과 처지에서 답하세요. 답마다 1~3문장, 실제로 말하듯 씁니다.
좋게 보이려고 꾸미지 마세요. 관심이 없으면 없다고, 모르겠으면 모르겠다고 답하면 됩니다.
설명에 없는 기능을 있다고 치지 마세요 — 설명만 보고 이해한 대로 답합니다.
"""


def build_prompt(card_text: str, board_text: str) -> str:
    """응답자 한 명이 보는 것 전부. 자극은 하나뿐이라 방향(fwd/rev)이 없다."""
    return TEMPLATE.replace("{CARD_TEXT}", card_text).replace("{BOARD}", board_text)
