def search_prompt(variant: str | None = None) -> tuple:
    """(변종이름, 문안). 모르는 이름이면 **조용히 기본으로 넘어가지 않고 멈춘다** —
    오타 하나로 측정이 다른 문안에서 돌면 그 실행을 통째로 못 쓴다."""
    name = variant or DEFAULT_SEARCH_VARIANT
    if name not in SEARCH_VARIANTS:
        raise KeyError(f"모르는 SEARCH 문안: {name!r} (있는 것: {sorted(SEARCH_VARIANTS)})")
    return name, SEARCH_VARIANTS[name]


