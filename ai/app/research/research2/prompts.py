def render_documents(docs: list, max_chars: int) -> str:
    """문서들을 번호와 함께 한 프롬프트에 담는다. 번호가 url 로 되돌아가는 열쇠다."""
    parts = []
    for i, d in enumerate(docs):
        parts.append(f"[문서 {i}] {d.url}\n\"\"\"\n{(d.text or '')[:max_chars]}\n\"\"\"")
    return "\n\n".join(parts)


