def render(tpl: str, **kw) -> str:
    """프롬프트 치환. str.format 을 쓰지 않는다 — JSON 뼈대의 중괄호가 깨진다."""
    out = tpl
    for k, v in kw.items():
        out = out.replace("{" + k + "}", str(v))
    return out


