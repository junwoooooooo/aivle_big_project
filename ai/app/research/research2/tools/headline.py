def _점수(카드: dict, spec: dict) -> tuple:
    """정렬 열쇠. **큰 것이 앞.** 잣대는 셋뿐이고 셋 다 업종을 안 탄다.

    ① **그 절의 물음에 답하는가** — 단위·가산어. 「무엇을 묻는가」에서 기계로 나온다
    ② **최신인가** — 연도. 어느 업종에서나 새 수가 낫다
    ③ **읽는 데 군더더기가 없는가** — 우리 시장 > 업계 전체 > 대체 > 회사 > 밖

    ⚠ **등급을 쓰지 않는다.** 이 판의 왕관 사실이 화이트리스트 때문에 「추정」이었다.
    """
    주제 = str(카드.get("주제") or "")
    글 = f"{주제} {카드.get('인용') or ''}"
    답 = 0
    if spec["찾는_단위"] and str(카드.get("단위") or "") in spec["찾는_단위"]:
        답 += 1
    for 낱말들 in spec["가산"].values():
        if any(w in 글 for w in 낱말들):
            답 += 1
    # **묻는 것에 답하지 않는 흔한 말은 깎는다.** 주제에만 건다 — 인용까지 보면
    # 「매출액」이 스치기만 해도 깎여, 진짜 이익률 문장이 같이 밀린다.
    if any(w in 주제 for w in spec.get("감점") or []):
        답 -= 2
    # 값을 못 읽은 것은 뒤로 — 단, **규제처럼 수가 없는 것이 정상인 절**은 안 깎는다
    if 카드.get("값") is None and spec["찾는_단위"]:
        답 -= 1
    # ⚠ **연도 칸이 늘 네 자리 수는 아니다.** 실측: `기간 = "지난해 "` 가 들어 있다 —
    #   모델이 원문 표현을 그대로 옮긴 것이다. **고쳐 쓰지 않고 「모름」으로 둔다**(0).
    # ★ **값 «유형»이 최신성보다 앞이다** (판 ㊹ 6단계 판정 반영).
    #   실측: 경쟁 절에서 「온더고 점유율 20%」가 최신 분기의 「당기 매출비중 6.1%」에 졌다.
    #   물음이 「그 자리에 누가 얼마나」인데 답이 아닌 것이 이겼다 — 잣대가 사실상
    #   최신성만 작동한 것이다. 유형은 **업종을 안 탄다**(미용실에 대입해도 성립).
    유형표 = spec.get("값유형") or []
    유형 = 0
    for i, 낱말들 in enumerate(유형표):
        if any(w in 주제 for w in 낱말들):
            유형 = len(유형표) - i
            break
    m = __import__("re").search(r"(19|20)\d{2}", str(카드.get("기간") or ""))
    해 = int(m.group(0)) if m else 0
    가까움 = ["OURS_SEGMENT", "OURS_UMBRELLA", "SUBSTITUTE", "COMPETITOR_FIRM", PG.DRAWER]
    자리 = len(가까움) - (가까움.index(카드.get("_갈래")) if 카드.get("_갈래") in 가까움 else len(가까움))
    return (유형, 답, 해, 자리)


def _서랍표(카드들: list) -> str:
    """서랍 라벨은 **건수가 아니라 대표값 한 줄**이다.

    ⚠ 「밖 258건」은 **열 이유를 주지 않는다.** 「식품제조업 전체 188.8조 — 상한으로만 ·
      외 34건」이라야 사업가가 열지 말지를 정할 수 있다.
    """
    if not 카드들:
        return ""
    # ⚠ **잡동사니 첫 행이 아니라 «그 절의 2~4등»을 낸다** (판 ㊹ 6단계 판정).
    #   실측: 경쟁 절 서랍 라벨이 「36,745억원 — 오뚜기」였는데, 그 서랍 안에 진짜
    #   열 이유인 **「온더고 점유율 20%」**가 들어 있었다. 라벨이 열 이유를 가렸다.
    앞 = 카드들[0]
    꼬리 = f" · 외 {len(카드들) - 1}건" if len(카드들) > 1 else ""
    return f"{앞.get('주제')} {앞.get('_원문값')} — {정체(앞)}{꼬리}"


def build(publish: dict, 카드들: list) -> dict:
    """절마다 `{머리: [...], 서랍: [...], 서랍_라벨: str, 묻는_것: str}`.

    ⚠ **아무것도 버리지 않는다.** 머리에 안 선 것은 전부 서랍에 있고, 서랍은 라벨이 붙는다.
    """
    # ── 같은 절 안의 **같은 값 중복**을 접는다 ─────────────────
    # ⚠ 게재 층의 중복 접기는 «사실» 단위라, 승격 «카드»에는 표기만 다른 쌍이 남는다.
    #   실측: 시장 크기 절 머리에 「컬리 거래액 3조 5,340억원」과 「3조 5,340억 원원」이
    #   **나란히** 섰다 — 사업가에게 근거가 둘로 보이지만 하나다.
    절별: dict = {}
    봄: set = set()
    for c in 카드들:
        sec = c.get("_절") or ""
        k = (sec, SY._수값(c.get("_원문값") or ""), str(c.get("주제") or "")[:16])
        if k[1] >= 0 and k in 봄:
            continue
        봄.add(k)
        절별.setdefault(sec, []).append(c)

    out = {}
    for sec, cs in 절별.items():
        spec = 물음.get(sec)
        if not spec:                       # 모르는 절은 **손대지 않는다**
            out[sec] = {"머리": cs, "서랍": [], "서랍_라벨": "", "묻는_것": ""}
            continue
        # ★ **서랍(`밖`)은 머리 후보가 아니다.** 게이트가 이미 「우리 주제 밖」이라고
        #   판정한 것을 그대로 읽는 것이지, 게이트를 여기서 다시 세우는 게 아니다.
        #   ⚠ 이것은 「우리 카테고리와의 거리」가 **아니다** — `OURS_UMBRELLA`(업계 전체)는
        #     머리 후보로 남는다. 목표 보고서 6절 머릿값 「식료품 제조업 영업이익률」이
        #     산업 전체 값이라, 그것까지 밀어내면 그 절이 영영 안 선다.
        #   ⚠ **모자라면 서랍에서 채운다** — 절을 비워 두는 것이 더 나쁘다.
        후보 = sorted((c for c in cs if c.get("_갈래") != PG.DRAWER),
                     key=lambda c: _점수(c, spec), reverse=True)
        나머지 = sorted((c for c in cs if c.get("_갈래") == PG.DRAWER),
                      key=lambda c: _점수(c, spec), reverse=True)
        차례 = 후보 + 나머지
        # ⚠ **같은 지표의 다른 연도가 머리 두 자리를 먹지 않게 한다** (판 ㊹ 6단계 재판정).
        #   실측: 가격 절 머리를 「냉동식품 판매단가」 2개년(6,513·6,296)이 차지해
        #   배달 비교의 근거값이 통째로 서랍으로 밀렸다. **같은 말은 한 번만 세운다.**
        머리, 남 = [], []
        본주제: set = set()
        for c in 차례:
            키 = str(c.get("주제") or "").strip()[:20]
            if len(머리) < TOP_N and 키 not in 본주제:
                본주제.add(키)
                머리.append(c)
            else:
                남.append(c)
        서랍 = 남
        # 서랍도 **같은 순서**로 둔다 — 「우리 주제 밖」이 맨 뒤로 가고 열 만한 것이 앞에 온다
        out[sec] = {"머리": 머리, "서랍": 서랍,
                    "서랍_라벨": _서랍표(서랍), "묻는_것": spec["묻는_것"]}
    return out


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("publish")
    a = ap.parse_args()

    import promote_cards as PROMOTE                                # noqa: PLC0415
    pub = json.load(io.open(a.publish, encoding="utf-8"))
    카드 = PROMOTE.build(pub)
    got = build(pub, 카드)

    print(f"\n승격 {len(카드)}장 → 절 {len(got)}개\n")
    for sec, v in sorted(got.items()):
        print(f"── {sec} — {v['묻는_것']}")
        for c in v["머리"]:
            print(f"   ★ {str(c.get('주제'))[:40]:<42}{str(c.get('_원문값'))[:16]:<18}"
                  f"{str(c.get('기간') or '연도 없음'):<10}{정체(c)}")
        if v["서랍"]:
            print(f"   ▸ 서랍 {len(v['서랍'])}건 — {v['서랍_라벨']}")
        print()
    빈 = [s for s, v in got.items() if not v["머리"]]
    if 빈:
        print("⚠ 머리가 빈 절:", " · ".join(빈))
    print("정체 —", " · ".join(f"{k} {n}" for k, n in
                             Counter(정체(c) for c in 카드).most_common(6)))
    return 0


