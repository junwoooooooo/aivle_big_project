CREATE TABLE concept_rule_traces (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assessment_id BIGINT NOT NULL,
    boundary_rule_id BIGINT NOT NULL,
    compliance_status VARCHAR(40) NOT NULL,
    concept_field_paths_json TEXT NOT NULL,
    implementation_controls_json TEXT NOT NULL,
    partner_dependencies_json TEXT NOT NULL,
    prohibited_variant TEXT,
    evidence_ids_json TEXT NOT NULL,
    explanation TEXT NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    deleted_at TIMESTAMP,
    version BIGINT NOT NULL,
    CONSTRAINT fk_concept_rule_trace_assessment FOREIGN KEY (assessment_id) REFERENCES concept_legal_assessments(id) ON DELETE NO ACTION,
    CONSTRAINT fk_concept_rule_trace_rule FOREIGN KEY (boundary_rule_id) REFERENCES boundary_rules(id) ON DELETE NO ACTION,
    CONSTRAINT uk_concept_rule_trace_rule UNIQUE (assessment_id, boundary_rule_id),
    CONSTRAINT ck_concept_rule_trace_status CHECK (compliance_status IN ('SATISFIED','SATISFIED_WITH_CONTROLS','REDESIGN_REQUIRED','INSUFFICIENT_INFORMATION','HARD_BLOCK'))
