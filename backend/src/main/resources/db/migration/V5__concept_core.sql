CREATE TABLE concept_exploration_batches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL,
    brief_version_id BIGINT NOT NULL,
    boundary_version_id BIGINT NOT NULL,
    task_run_id VARCHAR(64) NOT NULL,
    brief_snapshot_hash VARCHAR(71) NOT NULL,
    boundary_snapshot_hash VARCHAR(71) NOT NULL,
    input_snapshot_hash VARCHAR(71) NOT NULL,
    status VARCHAR(30) NOT NULL,
    eligible_count INTEGER NOT NULL DEFAULT 0,
    inspected_candidates INTEGER NOT NULL DEFAULT 0,
    current_round INTEGER NOT NULL DEFAULT 0,
    max_replacement_rounds INTEGER NOT NULL DEFAULT 2,
    max_inspected_candidates INTEGER NOT NULL DEFAULT 9,
    failure_code VARCHAR(100),
    needs_input_json TEXT NOT NULL DEFAULT '[]',
    completed_at TIMESTAMP,
    stale_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    deleted_at TIMESTAMP,
    version BIGINT NOT NULL,
    CONSTRAINT fk_concept_exploration_project FOREIGN KEY (project_id) REFERENCES projects(id) ON DELETE NO ACTION,
    CONSTRAINT fk_concept_exploration_brief FOREIGN KEY (brief_version_id) REFERENCES opportunity_brief_versions(id) ON DELETE NO ACTION,
    CONSTRAINT fk_concept_exploration_boundary FOREIGN KEY (boundary_version_id) REFERENCES regulatory_boundary_versions(id) ON DELETE NO ACTION,
    CONSTRAINT fk_concept_exploration_task FOREIGN KEY (task_run_id) REFERENCES task_runs(id) ON DELETE NO ACTION,
    CONSTRAINT uk_concept_exploration_task UNIQUE (task_run_id),
    CONSTRAINT uk_concept_exploration_input UNIQUE (project_id, brief_version_id, boundary_version_id, input_snapshot_hash),
    CONSTRAINT ck_concept_exploration_status CHECK (status IN ('QUEUED','GENERATING','VALIDATING','REPLACING','COMPLETED','NEEDS_INPUT','FAILED','STALE')),
    CONSTRAINT ck_concept_exploration_counts CHECK (eligible_count BETWEEN 0 AND 3 AND inspected_candidates BETWEEN 0 AND max_inspected_candidates)
);

CREATE TABLE concept_slots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id BIGINT NOT NULL,
    slot_index INTEGER NOT NULL,
    variation_focus VARCHAR(50) NOT NULL,
    status VARCHAR(40) NOT NULL,
    current_phase VARCHAR(20) NOT NULL,
    attempt_count INTEGER NOT NULL DEFAULT 0,
    legal_state VARCHAR(40),
    eligible BOOLEAN NOT NULL DEFAULT FALSE,
    safe_message_key VARCHAR(120) NOT NULL,
    replacement_for_slot_id BIGINT,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    deleted_at TIMESTAMP,
    version BIGINT NOT NULL,
    CONSTRAINT fk_concept_slot_batch FOREIGN KEY (batch_id) REFERENCES concept_exploration_batches(id) ON DELETE NO ACTION,
    CONSTRAINT fk_concept_slot_replacement FOREIGN KEY (replacement_for_slot_id) REFERENCES concept_slots(id) ON DELETE NO ACTION,
    CONSTRAINT uk_concept_slot_index UNIQUE (batch_id, slot_index),
    CONSTRAINT ck_concept_slot_focus CHECK (variation_focus IN ('TARGET_AND_USER_EXPERIENCE','OPERATING_MODEL_AND_PARTNERS','REVENUE_AND_CHANNELS')),
    CONSTRAINT ck_concept_slot_phase CHECK (current_phase IN ('INITIAL','REPAIR','REDESIGN','REPLACEMENT')),
    CONSTRAINT ck_concept_slot_status CHECK (status IN ('QUEUED','GENERATING','GENERATED','SCHEMA_INVALID','TRANSIENT_PROVIDER_FAILURE','PERMANENT_PROVIDER_FAILURE','VALIDATING_ORIGIN','VALIDATING_BOUNDARY','REDESIGNING','REPLACING','ELIGIBLE','REJECTED','NEEDS_INPUT','FAILED','STALE')),
    CONSTRAINT ck_concept_slot_legal CHECK (legal_state IS NULL OR legal_state IN ('IMPLEMENTABLE','IMPLEMENTABLE_WITH_CONTROLS','REDESIGN_REQUIRED','INSUFFICIENT_INFORMATION','HARD_BLOCK'))
);

CREATE TABLE concept_attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slot_id BIGINT NOT NULL,
    attempt_number INTEGER NOT NULL,
    phase VARCHAR(20) NOT NULL,
    outcome VARCHAR(40) NOT NULL,
    provider_failure_type VARCHAR(40),
    candidate_json TEXT,
    concept_snapshot_hash VARCHAR(71),
    duplicate_status VARCHAR(20),
    duplicate_key VARCHAR(71),
    negative_constraint_json TEXT NOT NULL DEFAULT '{}',
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    deleted_at TIMESTAMP,
    version BIGINT NOT NULL,
    CONSTRAINT fk_concept_attempt_slot FOREIGN KEY (slot_id) REFERENCES concept_slots(id) ON DELETE NO ACTION,
    CONSTRAINT uk_concept_attempt_sequence UNIQUE (slot_id, attempt_number),
    CONSTRAINT ck_concept_attempt_phase CHECK (phase IN ('INITIAL','REPAIR','REDESIGN','REPLACEMENT')),
    CONSTRAINT ck_concept_attempt_outcome CHECK (outcome IN ('VALID','SCHEMA_INVALID','TRANSIENT_PROVIDER_FAILURE','PERMANENT_PROVIDER_FAILURE')),
    CONSTRAINT ck_concept_attempt_duplicate CHECK (duplicate_status IS NULL OR duplicate_status IN ('UNIQUE','NEAR_DUPLICATE','DUPLICATE'))
);

CREATE TABLE concept_origin_validations (
