CREATE TABLE exploration_concepts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL,
    batch_id BIGINT NOT NULL,
    slot_id BIGINT NOT NULL,
    concept_attempt_id BIGINT NOT NULL,
    display_order INTEGER NOT NULL,
    concept_name VARCHAR(200) NOT NULL,
    skeleton_json TEXT NOT NULL,
    legal_state VARCHAR(40) NOT NULL,
    assessment_version INTEGER NOT NULL DEFAULT 1,
    validated_snapshot_hash VARCHAR(71) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    deleted_at TIMESTAMP,
    version BIGINT NOT NULL,
    CONSTRAINT fk_exploration_concept_project FOREIGN KEY (project_id) REFERENCES projects(id) ON DELETE NO ACTION,
    CONSTRAINT fk_exploration_concept_batch FOREIGN KEY (batch_id) REFERENCES concept_exploration_batches(id) ON DELETE NO ACTION,
    CONSTRAINT fk_exploration_concept_slot FOREIGN KEY (slot_id) REFERENCES concept_slots(id) ON DELETE NO ACTION,
    CONSTRAINT fk_exploration_concept_attempt FOREIGN KEY (concept_attempt_id) REFERENCES concept_attempts(id) ON DELETE NO ACTION,
    CONSTRAINT uk_exploration_concept_slot UNIQUE (slot_id),
    CONSTRAINT uk_exploration_concept_order UNIQUE (batch_id, display_order),
    CONSTRAINT uk_exploration_concept_hash UNIQUE (validated_snapshot_hash),
    CONSTRAINT ck_exploration_concept_legal CHECK (legal_state IN ('IMPLEMENTABLE','IMPLEMENTABLE_WITH_CONTROLS'))
);

CREATE INDEX idx_concept_exploration_current ON concept_exploration_batches(project_id, created_at DESC, id DESC);
CREATE INDEX idx_concept_slots_batch ON concept_slots(batch_id, slot_index);
CREATE INDEX idx_concept_attempts_slot ON concept_attempts(slot_id, attempt_number);
CREATE INDEX idx_exploration_concepts_public ON exploration_concepts(project_id, batch_id, display_order);
