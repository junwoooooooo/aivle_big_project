-- 타당성 결과를 시장·비즈니스 모델·기술 운영 3묶음으로 종합한다.
-- 차원 10행(feasibility_dimension_results)은 그대로 두고 그 위에 묶음 계층을 얹는다.
-- score/verdict 는 묶음 가중치로 정규화한 결정론 계산값이고 나머지 텍스트는 AI 서술이다.
CREATE TABLE feasibility_group_results (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    feasibility_assessment_id BIGINT NOT NULL,
    analysis_type VARCHAR(40) NOT NULL,
    display_order INTEGER NOT NULL,
    score INTEGER,
    verdict VARCHAR(40) NOT NULL,
    headline TEXT,
    summary TEXT,
    strengths_json TEXT,
    risks_json TEXT,
    next_focus TEXT,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    deleted_at TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_feasibility_group_assessment
        FOREIGN KEY (feasibility_assessment_id) REFERENCES feasibility_assessments(id),
    CONSTRAINT ck_feasibility_group_score CHECK (score IS NULL OR score BETWEEN 0 AND 100),
    CONSTRAINT uk_feasibility_group UNIQUE (feasibility_assessment_id, analysis_type)
);
CREATE INDEX idx_feasibility_group_assessment
    ON feasibility_group_results(feasibility_assessment_id);
