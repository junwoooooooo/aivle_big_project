CREATE TABLE concept_legal_regulatory_reports (
    id VARCHAR(64) PRIMARY KEY,
    project_id BIGINT NOT NULL,
    selection_id BIGINT NOT NULL,
    concept_id VARCHAR(64) NOT NULL,
    status VARCHAR(20) NOT NULL,
    schema_version VARCHAR(20) NOT NULL,
    selected_concept_hash VARCHAR(71) NOT NULL,
    hypothesis_snapshot_hash VARCHAR(71) NOT NULL,
    base_legal_hash VARCHAR(71) NOT NULL,
    delta_legal_hash VARCHAR(71),
    official_evidence_hash VARCHAR(71) NOT NULL,
    report_json TEXT NOT NULL,
    report_hash VARCHAR(71) NOT NULL,
    basis_date DATE NOT NULL,
    created_by_user_id BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    deleted_at TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uk_cp_legal_report_id_project UNIQUE (id, project_id),
    CONSTRAINT fk_cp_legal_report_selection FOREIGN KEY (selection_id, project_id)
        REFERENCES concept_portfolio_selections(id, project_id) ON DELETE NO ACTION,
    CONSTRAINT fk_cp_legal_report_concept FOREIGN KEY (concept_id, project_id)
        REFERENCES concept_portfolio_concepts(id, project_id) ON DELETE NO ACTION,
    CONSTRAINT fk_cp_legal_report_user FOREIGN KEY (created_by_user_id) REFERENCES users(id) ON DELETE NO ACTION,
    CONSTRAINT ck_cp_legal_report_status CHECK (status IN ('CURRENT', 'STALE')),
    CONSTRAINT ck_cp_legal_report_hashes CHECK (
        selected_concept_hash LIKE 'sha256:%' AND hypothesis_snapshot_hash LIKE 'sha256:%'
        AND base_legal_hash LIKE 'sha256:%' AND (delta_legal_hash IS NULL OR delta_legal_hash LIKE 'sha256:%')
        AND official_evidence_hash LIKE 'sha256:%' AND report_hash LIKE 'sha256:%')
);
CREATE UNIQUE INDEX uk_cp_legal_report_current ON concept_legal_regulatory_reports(selection_id)
    WHERE status = 'CURRENT' AND deleted_at IS NULL;

