CREATE TABLE twin_survey_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL,
    task_run_id VARCHAR(64) NOT NULL,
    source_market_seed_snapshot_id VARCHAR(64) NOT NULL,
    source_portfolio_selection_id BIGINT NOT NULL,
    source_selection_revision INTEGER NOT NULL,
    input_snapshot_hash VARCHAR(71) NOT NULL,
    sample_size INTEGER NOT NULL,
    state VARCHAR(20) NOT NULL,
    error_code VARCHAR(80),
    completed_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    deleted_at TIMESTAMP,
    version BIGINT NOT NULL,
    CONSTRAINT fk_twin_survey_run_project FOREIGN KEY (project_id) REFERENCES projects(id) ON DELETE NO ACTION,
    CONSTRAINT fk_twin_survey_run_task FOREIGN KEY (task_run_id) REFERENCES task_runs(id) ON DELETE NO ACTION,
    CONSTRAINT fk_twin_survey_run_seed FOREIGN KEY (source_market_seed_snapshot_id) REFERENCES market_analysis_seed_snapshots(id) ON DELETE NO ACTION,
    CONSTRAINT fk_twin_survey_run_selection FOREIGN KEY (source_portfolio_selection_id) REFERENCES concept_portfolio_selections(id) ON DELETE NO ACTION,
    CONSTRAINT uk_twin_survey_run_task UNIQUE (task_run_id),
    CONSTRAINT ck_twin_survey_run_state CHECK (state IN ('QUEUED', 'RUNNING', 'SUCCEEDED', 'FAILED')),
    CONSTRAINT ck_twin_survey_run_sample_size CHECK (sample_size IN (50, 100, 300)),
    CONSTRAINT ck_twin_survey_run_selection_revision CHECK (source_selection_revision >= 0)
);
CREATE INDEX idx_twin_survey_runs_project ON twin_survey_runs(project_id, created_at DESC);
CREATE TABLE twin_survey_versions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL,
    source_run_id BIGINT NOT NULL,
    version_number INTEGER NOT NULL,
    result_json TEXT NOT NULL,
    sample_size INTEGER NOT NULL,
    pair_count INTEGER NOT NULL,
    measurable_count INTEGER NOT NULL,
    caveat_count INTEGER NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    deleted_at TIMESTAMP,
    version BIGINT NOT NULL,
    CONSTRAINT fk_twin_survey_version_project FOREIGN KEY (project_id) REFERENCES projects(id) ON DELETE NO ACTION,
    CONSTRAINT fk_twin_survey_version_run FOREIGN KEY (source_run_id) REFERENCES twin_survey_runs(id) ON DELETE NO ACTION,
    CONSTRAINT uk_twin_survey_version_run UNIQUE (source_run_id),
    CONSTRAINT uk_twin_survey_version_number UNIQUE (project_id, version_number)
);
CREATE INDEX idx_twin_survey_versions_project ON twin_survey_versions(project_id, version_number DESC);
